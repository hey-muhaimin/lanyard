// Package authstore is a thin adapter over the SECURITY DEFINER functions in
// migrations/003_auth.sql. Codes and tokens are hashed by the caller; this
// package never reads login_codes or sessions directly and never reimplements
// the hashing or throttling logic that lives in SQL.
package authstore

import (
	"context"
	"errors"
	"fmt"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// defaultPolicyBody is the Cedar policy published for a newly registered
// tenant so /grant is not denied outright.
const defaultPolicyBody = `permit (principal is Agent, action, resource is Resource) when { principal.status == "active" && principal.tenantId == context.tenantId && context.connector == resource.connector && context.rowLimit <= 1000 && context.ttlSeconds <= 600 };`

// Member is the subset of members returned by auth_verify_login.
type Member struct {
	MemberID string
	TenantID string
	Role     string
}

// Session is the subset of sessions/members returned by auth_get_session.
type Session struct {
	MemberID string
	TenantID string
	Email    string
	Role     string
}

// Store adapts a pgx pool to the auth SQL functions.
type Store struct {
	pool *pgxpool.Pool
}

// New constructs a Store backed by the supplied pool.
func New(pool *pgxpool.Pool) *Store {
	return &Store{pool: pool}
}

// RequestCode stores sha256(code) for an active member. It reports false when
// the email is unknown or the member requested a code less than 30 seconds ago.
func (s *Store) RequestCode(ctx context.Context, email string, codeHash []byte, expires time.Time) (bool, error) {
	var stored bool
	err := s.pool.QueryRow(ctx,
		`SELECT auth_request_login($1, $2, $3)`,
		email, codeHash, expires,
	).Scan(&stored)
	if err != nil {
		return false, fmt.Errorf("request login code: %w", err)
	}
	return stored, nil
}

// VerifyCode consumes a matching code and returns the member it belongs to.
func (s *Store) VerifyCode(ctx context.Context, email string, codeHash []byte) (Member, bool, error) {
	var member Member
	err := s.pool.QueryRow(ctx,
		`SELECT member_id, tenant_id, role FROM auth_verify_login($1, $2)`,
		email, codeHash,
	).Scan(&member.MemberID, &member.TenantID, &member.Role)
	if errors.Is(err, pgx.ErrNoRows) {
		return Member{}, false, nil
	}
	if err != nil {
		return Member{}, false, fmt.Errorf("verify login code: %w", err)
	}
	return member, true, nil
}

// CreateSession stores sha256(token) for an active member.
func (s *Store) CreateSession(ctx context.Context, tokenHash []byte, memberID string, expires time.Time) error {
	if _, err := s.pool.Exec(ctx,
		`SELECT auth_create_session($1, $2::uuid, $3)`,
		tokenHash, memberID, expires,
	); err != nil {
		return fmt.Errorf("create session: %w", err)
	}
	return nil
}

// GetSession resolves a live session, refreshing its last-seen timestamp. It
// reports false when the token is unknown, expired, or idle past idle.
func (s *Store) GetSession(ctx context.Context, tokenHash []byte, idle time.Duration) (Session, bool, error) {
	var session Session
	err := s.pool.QueryRow(ctx,
		`SELECT member_id, tenant_id, email, role FROM auth_get_session($1, make_interval(secs => $2))`,
		tokenHash, int64(idle.Seconds()),
	).Scan(&session.MemberID, &session.TenantID, &session.Email, &session.Role)
	if errors.Is(err, pgx.ErrNoRows) {
		return Session{}, false, nil
	}
	if err != nil {
		return Session{}, false, fmt.Errorf("get session: %w", err)
	}
	return session, true, nil
}

// EndSession deletes a session. Unknown tokens are a no-op.
func (s *Store) EndSession(ctx context.Context, tokenHash []byte) error {
	if _, err := s.pool.Exec(ctx, `SELECT auth_end_session($1)`, tokenHash); err != nil {
		return fmt.Errorf("end session: %w", err)
	}
	return nil
}

// CreateTenantWithAdmin creates a tenant, its first (admin) member, and the
// default published Cedar policy in one transaction. Tenant and policy IDs are
// generated by Postgres so callers cannot supply them.
func (s *Store) CreateTenantWithAdmin(ctx context.Context, tenantName, email, role string) (string, error) {
	if strings.TrimSpace(tenantName) == "" {
		return "", errors.New("tenant name is required")
	}
	if strings.TrimSpace(email) == "" {
		return "", errors.New("email is required")
	}

	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return "", fmt.Errorf("begin registration transaction: %w", err)
	}
	defer func() { _ = tx.Rollback(context.Background()) }()

	var tenantID string
	if err := tx.QueryRow(ctx,
		`SELECT create_tenant(gen_random_uuid(), $1)`, tenantName,
	).Scan(&tenantID); err != nil {
		return "", fmt.Errorf("create tenant: %w", err)
	}
	if _, err := tx.Exec(ctx,
		`SELECT set_config('app.tenant_id', $1, true)`, tenantID,
	); err != nil {
		return "", fmt.Errorf("set tenant transaction context: %w", err)
	}
	if _, err := tx.Exec(ctx,
		`INSERT INTO members (tenant_id, email, role, status) VALUES ($1, $2, $3, 'active')`,
		tenantID, strings.ToLower(strings.TrimSpace(email)), role,
	); err != nil {
		return "", fmt.Errorf("create admin member: %w", err)
	}
	if _, err := tx.Exec(ctx,
		`INSERT INTO policies (id, tenant_id, version, body, status)
		 VALUES (gen_random_uuid(), $1, 1, $2, 'published')`,
		tenantID, defaultPolicyBody,
	); err != nil {
		return "", fmt.Errorf("publish default policy: %w", err)
	}
	if err := tx.Commit(ctx); err != nil {
		return "", fmt.Errorf("commit registration transaction: %w", err)
	}
	return tenantID, nil
}
